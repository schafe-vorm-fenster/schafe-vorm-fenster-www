/**
 * Blur previews for `photo-surface` — issue 236.
 *
 * A photo surface paints its photograph as a CSS background. On a client
 * navigation the file is not cached yet, so the section shows its bare
 * gradient until the first bytes decode. This script renders every image under
 * `public/images` as a tiny blurred WebP data URI (≤ 1 KB), written to
 * `src/components/photo-surface/blur-map.generated.ts`, which `photo-surface`
 * lays beneath the real image as a lower background layer.
 *
 *   pnpm generate:photo-blur   regenerate the map
 *   pnpm check:photo-blur      fail when the map is stale
 *
 * Staleness is judged by the sources, not by the output bytes: each entry
 * carries the sha256 of the file it was made from, and the check compares the
 * file set and those hashes. libvips can differ in the last bit between
 * platforms, so comparing re-encoded bytes would fail on CI for no reason; the
 * check does enforce the 1 KB ceiling and the data-URI shape of every entry.
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, relative, sep } from "node:path";

import sharp from "sharp";

const ROOT = join(import.meta.dirname, "..");
const IMAGES = join(ROOT, "public", "images");
const OUT = join(ROOT, "src", "components", "photo-surface", "blur-map.generated.ts");

/** Width of the preview in pixels; the height follows the aspect ratio. */
const PREVIEW_WIDTH = 32;
/** The issue's ceiling for one data URI, in characters. */
const MAX_URI_LENGTH = 1024;

interface Entry {
  readonly sha256: string;
  readonly uri: string;
}

function walk(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true })
    .flatMap((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]))
    .filter((f) => /\.(webp|jpe?g|png|avif)$/i.test(f))
    .sort();
}

function urlOf(file: string): string {
  return "/" + relative(join(ROOT, "public"), file).split(sep).join("/");
}

function sha(file: string): string {
  return createHash("sha256").update(readFileSync(file)).digest("hex");
}

async function preview(file: string): Promise<string> {
  for (const quality of [60, 45, 30, 20, 10]) {
    const buf = await sharp(file)
      .resize({ width: PREVIEW_WIDTH })
      .blur(1)
      .webp({ quality, effort: 6, smartSubsample: true })
      .toBuffer();
    const uri = `data:image/webp;base64,${buf.toString("base64")}`;
    if (uri.length <= MAX_URI_LENGTH) return uri;
  }
  throw new Error(`generate-photo-blur: ${file} does not fit ${MAX_URI_LENGTH} characters`);
}

function render(map: Record<string, Entry>): string {
  const body = Object.keys(map)
    .sort()
    .map((k) => `  ${JSON.stringify(k)}: {\n    sha256: ${JSON.stringify(map[k].sha256)},\n    uri: ${JSON.stringify(map[k].uri)},\n  },`)
    .join("\n");
  return `/* eslint-disable */
// GENERATED by scripts/generate-photo-blur.ts — do not edit. Run \`pnpm generate:photo-blur\`.

export const PHOTO_BLUR: Readonly<Record<string, { readonly sha256: string; readonly uri: string }>> = {
${body}
};
`;
}

async function readCommitted(): Promise<Record<string, Entry>> {
  if (!existsSync(OUT)) return {};
  const mod = (await import(`${OUT}?t=${Date.now()}`)) as { PHOTO_BLUR: Record<string, Entry> };
  return mod.PHOTO_BLUR;
}

async function main(): Promise<void> {
  const check = process.argv.includes("--check");
  const files = walk(IMAGES);

  if (check) {
    const committed = await readCommitted();
    const errors: string[] = [];
    const expected = new Set(files.map(urlOf));
    for (const file of files) {
      const entry = committed[urlOf(file)];
      if (!entry) errors.push(`missing: ${urlOf(file)}`);
      else if (entry.sha256 !== sha(file)) errors.push(`stale: ${urlOf(file)}`);
      else if (!/^data:image\/webp;base64,[A-Za-z0-9+/=]+$/.test(entry.uri) || entry.uri.length > MAX_URI_LENGTH)
        errors.push(`malformed or over ${MAX_URI_LENGTH} characters: ${urlOf(file)}`);
    }
    for (const key of Object.keys(committed)) if (!expected.has(key)) errors.push(`orphan: ${key}`);
    if (errors.length > 0) {
      console.error(`check:photo-blur — ${errors.length} problem(s):\n  ${errors.join("\n  ")}\nRun \`pnpm generate:photo-blur\`.`);
      process.exit(1);
    }
    console.log(`check:photo-blur — ${files.length} previews current.`);
    return;
  }

  const committed = await readCommitted();
  const map: Record<string, Entry> = {};
  for (const file of files) {
    const hash = sha(file);
    const prior = committed[urlOf(file)];
    // Unchanged source keeps its committed bytes: the output stays stable
    // across platforms and library bumps until the picture itself changes.
    map[urlOf(file)] = prior && prior.sha256 === hash ? prior : { sha256: hash, uri: await preview(file) };
  }
  writeFileSync(OUT, render(map));
  const sizes = Object.values(map).map((e) => e.uri.length);
  console.log(`generate-photo-blur — ${files.length} previews, ${Math.min(...sizes)}–${Math.max(...sizes)} characters each.`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
